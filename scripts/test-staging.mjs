import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {randomUUID,randomBytes} from 'node:crypto';
import {createClient} from '@supabase/supabase-js';

// Deliberately pinned to the isolated Free project. No arbitrary remote target.
const credentials=JSON.parse(await fs.readFile('.test-cache/staging-credentials.json','utf8'));
const url='https://qmbwrbxbbshbavfhkujx.supabase.co';
assert.equal(credentials.url,url,'Only the approved staging project is permitted');
assert.ok(credentials.publishableKey.startsWith('sb_publishable_'));
assert.ok(credentials.secretKey.startsWith('sb_secret_'));
const options={auth:{persistSession:false,autoRefreshToken:false,detectSessionInUrl:false}};
const client=()=>createClient(url,credentials.publishableKey,options);
const admin=createClient(url,credentials.secretKey,options);
const host=client(),other=client(),guestA=client(),guestB=client(),reader=client();
const run=randomUUID(); const partyId='synthetic-'+run; const itemId=randomUUID();
const email='synthetic-'+run+'@example.test'; const password=randomBytes(32).toString('base64url');
const evidence={projectRef:'qmbwrbxbbshbavfhkujx',run,partyId,startedAt:new Date().toISOString(),checks:[]};
const checked=name=>{evidence.checks.push(name);console.log('PASS '+name);};
const ok=async result=>{const r=await result;if(r.error)throw new Error(r.error.code+': '+r.error.message);return r.data;};
const denied=async(result,pattern)=>{const r=await result;assert.ok(r.error,'Expected rejection');if(pattern)assert.match(r.error.message,pattern);};
const rpc=(c,name,args)=>ok(c.rpc('partyplus_v2_'+name,args));
const read=()=>rpc(reader,'read_party',{p_party_id:partyId});
const commit=(c,party,revision=0,op=randomUUID())=>rpc(c,'commit_party',{p_operation_id:op,p_expected_revision:revision,p_party:party});
const response=(c,op=randomUUID())=>rpc(c,'rsvp',{p_party_id:partyId,p_operation_id:op,p_response:{name:'Synthetic Guest',status:'yes',attendeeCount:2}});
const claim=c=>c.rpc('partyplus_v2_claim_item',{p_party_id:partyId,p_item_id:itemId,p_claim:true,p_operation_id:randomUUID()});
try {
  await ok(admin.auth.admin.createUser({email,password,email_confirm:true}));
  await ok(host.auth.signInWithPassword({email,password}));
  const hostId=(await ok(host.auth.getUser())).user.id;
  await ok(guestA.auth.signInAnonymously()); await ok(guestB.auth.signInAnonymously());
  assert.equal((await ok(guestA.auth.getUser())).user.is_anonymous,true);
  checked('Real verified host and distinct anonymous guest JWT sessions');
  const party={id:partyId,title:'Synthetic staging party',date:'2027-01-01T18:00:00Z',location:'Synthetic Hall',items:[{id:itemId,name:'Ice'}]};
  const op=randomUUID(); const created=await commit(host,party,0,op);
  assert.equal(created.committed,true); assert.equal(created.party.id,partyId);
  assert.deepEqual(await commit(host,party,0,op),created);
  await denied(host.rpc('partyplus_v2_commit_party',{p_operation_id:op,p_expected_revision:0,p_party:{...party,title:'Changed retry'}}),/operation_conflict/);
  checked('Stable create receipt, uncertain-outcome replay and changed-payload rejection');
  assert.equal((await read()).canEdit,false);
  await denied(reader.from('parties').select('*'));
  await denied(host.from('parties').update({title:'Unauthorized raw write'}).eq('id',partyId));
  await denied(guestA.from('party_rsvps').delete().eq('party_id',partyId));
  await denied(guestA.schema('partyplus_private').from('host_access').select('*'));
  await denied(guestA.rpc('partyplus_v2_commit_party',{p_operation_id:randomUUID(),p_expected_revision:0,p_party:{...party,id:partyId+'-guest'}}),/verified_host_required/);
  await denied(reader.rpc('partyplus_v2_rsvp',{p_party_id:partyId,p_operation_id:randomUUID(),p_response:{name:'Unsigned',status:'yes',attendeeCount:1}}));
  checked('Invitation read works; raw tables, private ledger and unsigned/anonymous host writes denied');
  const responseOp=randomUUID(); const receipts=await Promise.all([response(guestA,responseOp),response(guestA,responseOp),response(guestB)]);
  assert.deepEqual(receipts[0],receipts[1]); assert.equal((await read()).rsvps.length,2);
  const suggestions=[randomUUID(),randomUUID()];
  await Promise.all([guestA,guestB].map((c,i)=>rpc(c,'suggest_item',{p_party_id:partyId,p_item_id:suggestions[i],p_name:'Synthetic suggestion',p_operation_id:randomUUID()})));
  const claims=await Promise.all([claim(guestA),claim(guestB)]);
  assert.equal(claims.filter(r=>!r.error).length,1); assert.match(claims.find(r=>r.error).error.message,/claim_conflict/);
  const before=await read(); assert.equal(before.items.length,3);
  checked('Independent HTTP sessions retain same-name RSVPs, concurrent suggestions and one claim winner');
  const invalidId=partyId+'-invalid';
  await denied(host.rpc('partyplus_v2_commit_party',{p_operation_id:randomUUID(),p_expected_revision:0,p_party:{...party,id:invalidId,items:[{id:'invalid-uuid',name:'Invalid'}]}}));
  assert.equal(await rpc(reader,'read_party',{p_party_id:invalidId}),null);
  const edited=await commit(host,{...party,title:'Edited title',items:before.items},before.revision);
  assert.deepEqual(edited.party.rsvps,before.rsvps); assert.equal(edited.party.items.find(i=>i.id===itemId).claimedByUserId,before.items.find(i=>i.id===itemId).claimedByUserId);
  await denied(host.rpc('partyplus_v2_commit_party',{p_operation_id:randomUUID(),p_expected_revision:before.revision,p_party:party}),/revision_conflict/);
  await denied(host.rpc('partyplus_v2_commit_party',{p_operation_id:randomUUID(),p_expected_revision:null,p_party:party}),/revision_conflict/);
  assert.deepEqual(await read(),{...edited.party,canEdit:false});
  checked('Failed create rolls back; title edit preserves responses/claims; stale host revision rejected');
  const link=await ok(admin.auth.admin.generateLink({type:'magiclink',email}));
  await ok(other.auth.verifyOtp({email,token:link.properties.email_otp,type:'email'}));
  assert.equal((await ok(other.auth.getUser())).user.id,hostId);
  const returned=await rpc(other,'list_host_parties',{});assert.ok(returned.some(p=>p.id===partyId&&p.canEdit));
  const session=(await ok(host.auth.getSession())).session;
  await ok(host.auth.refreshSession({refresh_token:session.refresh_token}));
  assert.ok((await rpc(host,'list_host_parties',{})).some(p=>p.id===partyId));
  checked('Generated email OTP signs in on independent client; session refresh retains host access (no email delivered)');
  await denied(guestA.rpc('partyplus_v2_delete_party',{p_party_id:partyId,p_operation_id:randomUUID()}),/verified_host_required/);
  const deleteOp=randomUUID(); const deleted=await rpc(host,'delete_party',{p_party_id:partyId,p_operation_id:deleteOp});
  assert.deepEqual(await rpc(host,'delete_party',{p_party_id:partyId,p_operation_id:deleteOp}),deleted);
  assert.equal(await read(),null);
  checked('Authorized tombstone is replayable; guest deletion denied; invitation becomes unavailable');
  const otherSession=(await ok(other.auth.getSession())).session;
  await ok(host.auth.signOut({scope:'global'}));
  const revoked=await other.auth.refreshSession({refresh_token:otherSession.refresh_token});
  assert.ok(revoked.error,'Global sign-out must revoke the other client refresh token');
  checked('Global sign-out revokes independent client refresh; short-lived existing JWT validity is not claimed revoked');
  evidence.status='passed';
} catch(error) {evidence.status='failed';evidence.failure=error.message;throw error;}
finally {
  // Synthetic records are retained for inspection; do not purge Auth principals or ledgers.
  evidence.finishedAt=new Date().toISOString();
  await fs.writeFile('docs/staging-evidence-2026-10-02/real-auth-integration.json',JSON.stringify(evidence,null,2)+'\n');
  for(const c of [host,other,guestA,guestB])await c.auth.signOut({scope:'local'});
}
